  var urlLangRead = false;

  function readLangCookie() {
    var raw = "";
    try { raw = document.cookie || ""; } catch (err) { return ""; }
    var parts = raw.split(";");
    var prefix = "rmba_lang=";
    for (var i = 0; i < parts.length; i++) {
      var bit = parts[i].replace(/^\s+/, "");
      if (bit.indexOf(prefix) === 0) {
        try { return decodeURIComponent(bit.slice(prefix.length)); }
        catch (err2) { return ""; }
      }
    }
    return "";
  }

  function writeLangCookie(lang) {
    if (writeLangCookie.current === lang) return;
    writeLangCookie.current = lang;
    try {
      document.cookie = "rmba_lang=" + encodeURIComponent(lang) + "; path=/; max-age=31536000; SameSite=Lax";
    } catch (err) { /* ignore */ }
  }

  function getLang() {
    if (!urlLangRead && typeof location !== "undefined") {
      urlLangRead = true;
      var params = new URLSearchParams(location.search);
      var fromUrl = (params.get("lang") || "").toLowerCase();
      if (LANGS.indexOf(fromUrl) !== -1) {
        try { localStorage.setItem(KEY, fromUrl); } catch (err) { /* ignore */ }
        writeLangCookie(fromUrl);
        return fromUrl;
      }
    }
    var stored = "";
    try { stored = localStorage.getItem(KEY) || ""; } catch (err) { stored = ""; }
    if (LANGS.indexOf(stored) !== -1) {
      writeLangCookie(stored);
      return stored;
    }
    var fromCookie = readLangCookie();
    if (LANGS.indexOf(fromCookie) !== -1) return fromCookie;
    return "en";
  }

  function t(key, lang) {
    var code = lang || getLang();
    var table = STRINGS[code] || STRINGS.en;
    if (Object.prototype.hasOwnProperty.call(table, key) && table[key]) return table[key];
    if (code !== "en" && Object.prototype.hasOwnProperty.call(STRINGS.en, key)) return STRINGS.en[key];
    return key;
  }

  function applyI18n(root) {
    var scope = root || document;
    var lang = getLang();
    document.documentElement.lang = lang;
    if (document.body) {
      var titleKey = document.body.getAttribute("data-title-key");
      if (titleKey) document.title = t(titleKey);
    }
    scope.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach(function (node) {
      node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
    });
    scope.querySelectorAll("[data-i18n-alt]").forEach(function (node) {
      node.setAttribute("alt", t(node.getAttribute("data-i18n-alt")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (node) {
      node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
      node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-lang]").forEach(function (node) {
      var on = node.getAttribute("data-lang") === lang;
      node.setAttribute("aria-pressed", on ? "true" : "false");
    });
  }

  function setLang(lang) {
    if (LANGS.indexOf(lang) === -1) return;
    try { localStorage.setItem(KEY, lang); } catch (err) { /* private mode */ }
    writeLangCookie(lang);
    applyI18n(document);
    document.dispatchEvent(new CustomEvent("rmba:lang", { detail: { lang: lang } }));
  }

  document.addEventListener("click", function (event) {
    var button = event.target.closest("[data-lang]");
    if (!button) return;
    event.preventDefault();
    setLang(button.getAttribute("data-lang"));
  });

  window.RMBA = window.RMBA || {};
  window.RMBA.LANGS = LANGS;
  window.RMBA.t = t;
  window.RMBA.getLang = getLang;
  window.RMBA.setLang = setLang;
  window.RMBA.applyI18n = applyI18n;

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () { applyI18n(document); });
  } else {
    applyI18n(document);
  }
